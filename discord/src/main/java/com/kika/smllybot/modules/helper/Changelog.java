package com.kika.smllybot.modules.helper;

import com.kika.smllybot.other.BaseCmd;
import net.dv8tion.jda.api.components.container.Container;
import net.dv8tion.jda.api.components.textdisplay.TextDisplay;
import net.dv8tion.jda.api.events.message.MessageReceivedEvent;

import java.util.Set;

public class Changelog extends BaseCmd {

    public Changelog() {
        super(Set.of("чендж-лог", "ченджлог", "changelog"));
    }

    @Override
    public Container execute(MessageReceivedEvent event, String raw, String args) {

        var response = Container.of(
                TextDisplay.of("""
                        # 0.9.0-beta (28.11.2026)
                        ## ✨ Новое
                        - Поддержка слеш-команд!
                            - `ранний доступ`
                            - `анкета`
                            - `данет`
                            - `гильдия`
                            - `хелп`
                            - `ферма`
                            - `мут`
                            - `инфа`
                         - Поддержка инлайн-команд! (работают везде)
                            - `анкета`
                            - `данет`
                            - `хелп`
                            - `ферма`
                            - `инфа`
                        - Поддержка контекстных команд (ПКМ по нику пользователя)
                            - `анкета`
                        - `сбросить префиксы` / `удалить префиксы` - удаляет префиксы, установленные в гильдии
                        - Добавлена поддержка автокомплита в части команд
                        - Команды `мои баны` и `мои муты` работали только в гильдиях, вместо личных сообщений
                        - Модуль варнов!
                            - `варн` <число> <тип> <причина>⬇️ - выдает варн пользователю
                            - `снять варны` - снимает все варны с пользователя
                        ## 🐛 Исправлено
                        - Команда `ранний доступ` не работала из-за неверного названия таблицы с гильдиями (было guildInfo вместо guild)
                        - Часть склонений не поддерживались для мутов и банов
                        - Анкета не отображалась, если анкета вызывалась с помощью контекстной команды
                        - В гильдиях без установленных префиксов команды не работали совсем
                        - Нижняя граница для самого крупного выигрыша в ферме бралась из среднего выигрыша
                        - Планировщик не размучивал пользователей из-за попытки размутить по внутреннему инкрементальному айди, вместо использования айди дискорда
                        - Исправлен индекс в таблице WARN из-за которого нельзя было создавать более 1 варна
                        - Добавлена помощь по гильдиям в `хелп`
                        ## ⚙️ Внутренние изменения
                        - Большая часть команд перешла на централизованный обработчик ошибок
                        - Обработчик ошибок теперь отдает список контейнеров и не просит ничего взамен
                        - Команда `гильдия` теперь знает только о гильдии, а не в целом об MessageReceivedEvent
                        - Добавлены warn_role и warn_limit в таблицу guild для будущих обновлений
                        """)
        );

        event.getChannel().sendMessageComponents(response)
                .useComponentsV2(true)
                .queue();

        return null;
    }
}
